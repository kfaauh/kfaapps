  z<-DBI::dbGetQuery(con,"SELECT * FROM v_consumption_current_price WHERE varenummer='019307'")
  stopifnot(z$tsp_per_ddd==1,z$current_price_subsidy_basis_kr==z$ddd,z$linkage_status=='estimated_from_price_ratio')
